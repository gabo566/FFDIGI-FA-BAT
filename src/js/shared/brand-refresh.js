(() => {
    const brand = document.querySelector(".app-brand");
    if (!brand || brand.dataset.refreshed === "true") return;
    const logo = document.createElement("img");
    logo.className = "nvidia-wordmark";
    logo.src = "./assets/brand/LOGO NVIDIA NEGRO.png";
    logo.alt = "Logotipo NVIDIA";
    const racks = document.createElement("span");
    racks.className = "brand-racks";
    racks.textContent = "RACKS";
    racks.setAttribute("aria-label", "Racks");
    const ingrasys = document.createElement("img");
    ingrasys.className = "ingrasys-wordmark";
    ingrasys.src = "./assets/brand/ingrasys-logo-dark.png";
    ingrasys.alt = "Ingrasys";
    const divider = document.createElement("span");
    divider.className = "app-brand-divider";
    divider.setAttribute("aria-hidden", "true");
    const copy = document.createElement("div");
    copy.className = "app-brand-copy";
    const eyebrow = document.createElement("p");
    eyebrow.className = "app-brand-eyebrow";
    eyebrow.textContent = "DIAGNÓSTICO DE ENSAMBLE";
    const title = document.createElement("h1");
    title.className = "app-brand-title";
    title.textContent = "FFDG";
    const titleRow = document.createElement("div");
    titleRow.className = "app-brand-title-row";
    titleRow.append(title);
    const logout = document.getElementById("ffdg-logout");
    if (logout) titleRow.append(logout);
    const subtitle = document.createElement("p");
    subtitle.className = "app-brand-subtitle";
    subtitle.textContent = "Guía BAT / MTF / L11 · GB200 / GB300";
    copy.append(eyebrow, titleRow, subtitle);
    brand.replaceChildren(logo, racks, ingrasys, divider, copy);
    brand.dataset.refreshed = "true";
    document.title = "Nvidia Racks · FFDG · GB200 / GB300";
    document.querySelectorAll(".header-actions .fault-emblem").forEach(emblem => emblem.parentElement.remove());
  })();
